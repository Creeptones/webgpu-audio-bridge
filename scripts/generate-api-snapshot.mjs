// Member-level public API snapshots (0.9.948).
//
//   npm run api:snapshot        # write docs/api-snapshots/*.api.txt
//   npm run check:api-snapshot  # fail if any snapshot is stale
//
// Generated from the SOURCES by scripts/_apiSurface.mjs (TypeScript compiler
// API), so no build is needed. Each snapshot lists every export of the entry
// point with its full public shape (class members + signatures, interface
// properties, type-alias bodies, function signatures) plus the non-exported
// declarations the public surface reaches (e.g. `BridgeImpl` behind the
// `Bridge` alias). Adding, removing, renaming or retyping any public member
// changes the snapshot — the freeze gate 1.0 needs. (Until 0.9.947 the
// snapshot only captured `export { … } from` lines of `dist/index.d.ts`.)

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { apiSurface } from "./_apiSurface.mjs";

const root = new URL("../", import.meta.url);
const mode = process.argv.includes("--write") ? "write" : "check";

const ENTRIES = ["src/index.ts", "src/worklet/index.ts", "src/experimental/core.ts"];
const targets = [
  ["root (webgpu-audio-bridge)", "src/index.ts", "docs/api-snapshots/root.api.txt"],
  ["worklet (webgpu-audio-bridge/worklet)", "src/worklet/index.ts", "docs/api-snapshots/worklet.api.txt"],
  ["experimental (webgpu-audio-bridge/experimental[/core])", "src/experimental/core.ts", "docs/api-snapshots/experimental.api.txt"],
];
// Pre-0.9.948 export-line snapshots, superseded.
const LEGACY = ["docs/api-snapshots/root.dts.snapshot.txt", "docs/api-snapshots/experimental.dts.snapshot.txt"];

let failed = false;
mkdirSync(new URL("docs/api-snapshots/", root), { recursive: true });

for (const [label, entry, snapshotPath] of targets) {
  const { names, text } = apiSurface(entry, ENTRIES);
  const next = [
    `# ${label} — member-level public API snapshot`,
    `# Source: ${entry} (${names.length} exports). Generated by scripts/generate-api-snapshot.mjs.`,
    "# Do not edit by hand: run `npm run api:snapshot` after an intentional surface change.",
    "",
    text,
  ].join("\n");
  const snapshotUrl = new URL(snapshotPath, root);

  if (mode === "write") {
    writeFileSync(snapshotUrl, next, "utf8");
    console.log(`[api-snapshot] wrote ${snapshotPath} (${names.length} exports)`);
    continue;
  }
  if (!existsSync(snapshotUrl)) {
    console.error(`[api-snapshot] missing ${snapshotPath}; run npm run api:snapshot`);
    failed = true;
    continue;
  }
  const prev = readFileSync(snapshotUrl, "utf8").replace(/\r\n/g, "\n");
  if (prev !== next) {
    // Multiset diff: a member line can legitimately appear in several classes,
    // so compare occurrence counts rather than mere presence.
    const count = (lines) => lines.reduce((m, l) => m.set(l, (m.get(l) ?? 0) + 1), new Map());
    const ca = count(prev.split("\n"));
    const cb = count(next.split("\n"));
    const removed = [...ca].filter(([l, n]) => n > (cb.get(l) ?? 0)).map(([l]) => l).slice(0, 15);
    const added = [...cb].filter(([l, n]) => n > (ca.get(l) ?? 0)).map(([l]) => l).slice(0, 15);
    console.error(`[api-snapshot] ${snapshotPath} is stale — the public surface changed. If intentional, run npm run api:snapshot.`);
    for (const l of removed) console.error(`  - ${l}`);
    for (const l of added) console.error(`  + ${l}`);
    failed = true;
  }
}

if (mode === "write") {
  for (const p of LEGACY) {
    const u = new URL(p, root);
    if (existsSync(u)) { rmSync(u); console.log(`[api-snapshot] removed superseded ${p}`); }
  }
}

if (failed) process.exitCode = 1;
